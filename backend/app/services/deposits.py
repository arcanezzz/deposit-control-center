"""Deposit use-cases: create (idempotent), search, get details.

Idempotency contract
--------------------
* Scope: the Idempotency-Key is unique GLOBALLY (across all employees), with no expiry.
* Same key + same business data (employee, account, amount) -> the SAME deposit is returned
  (HTTP 200, idempotent_replay=true). No new deposit, no new Kafka message, no extra credit.
* Same key + different business data -> 409 IDEMPOTENCY_KEY_REUSED.
* Concurrent requests with the same key: the UNIQUE constraint + INSERT .. ON CONFLICT DO NOTHING
  guarantees exactly one row; the "loser" falls into the replay/conflict path.
* Simulation flags are NOT business data and are not compared (the first request wins).
"""
import hashlib
import json
import logging
import re
import uuid
from datetime import date
from decimal import Decimal

import asyncpg

from app.errors import ApiError
from app.schemas import DepositCreate

log = logging.getLogger(__name__)

IDEMPOTENCY_KEY_RE = re.compile(r"^[A-Za-z0-9_\-:.]{8,128}$")
VALID_STATUSES = {"PENDING", "PROCESSING", "COMPLETED", "FAILED"}

DEPOSIT_SELECT = """
    SELECT d.id, d.idempotency_key, d.employee_id, e.name AS employee_name,
           d.account_id, a.account_number, a.owner_name, d.amount, d.status,
           d.failure_code, d.failure_reason, d.failure_retryable, d.attempts,
           d.simulate_delay_seconds, d.simulate_transient_failure,
           d.processing_started_at, d.created_at, d.updated_at, d.completed_at, d.request_hash
      FROM deposits d
      JOIN employees e ON e.id = d.employee_id
      JOIN accounts  a ON a.id = d.account_id
"""


def request_hash(employee_id: str, account_id: str, amount: Decimal) -> str:
    # Same format as seed.sql: sha256("<employee>|<account>|<amount with 2 decimals>")
    return hashlib.sha256(f"{employee_id}|{account_id}|{amount:.2f}".encode("utf-8")).hexdigest()


def validate_idempotency_key(key: str | None) -> str:
    if key is None or key.strip() == "":
        raise ApiError(400, "IDEMPOTENCY_KEY_REQUIRED",
                       "Header Idempotency-Key is required (e.g. a UUID generated by the client)")
    key = key.strip()
    if not IDEMPOTENCY_KEY_RE.match(key):
        raise ApiError(400, "INVALID_IDEMPOTENCY_KEY",
                       "Idempotency-Key must be 8-128 characters of letters, digits, '-', '_', ':' or '.'")
    return key


def _public(row: asyncpg.Record) -> dict:
    data = dict(row)
    data.pop("request_hash", None)
    return data


async def _replay_or_conflict(conn: asyncpg.Connection, key: str, req_hash: str, employee_id: str) -> dict:
    existing = await conn.fetchrow(DEPOSIT_SELECT + " WHERE d.idempotency_key = $1", key)
    if existing["request_hash"] != req_hash:
        raise ApiError(409, "IDEMPOTENCY_KEY_REUSED",
                       "This Idempotency-Key was already used for a deposit with different data "
                       "(employee / account / amount). Use a new key for a new deposit.",
                       {"existing_deposit_id": str(existing["id"])})
    # Record the replay in the timeline so an investigator can see the double-click / resend.
    await conn.execute(
        """INSERT INTO deposit_events (deposit_id, event_type, actor_employee_id, details)
           VALUES ($1, 'IDEMPOTENT_REPLAY', $2, $3::jsonb)""",
        existing["id"], employee_id if await _employee_exists(conn, employee_id) else None,
        json.dumps({"idempotency_key": key, "status_at_replay": existing["status"]}),
    )
    log.info("idempotent replay", extra={"deposit_id": existing["id"], "status": existing["status"]})
    return _public(existing)


async def _employee_exists(conn: asyncpg.Connection, employee_id: str) -> bool:
    return await conn.fetchval("SELECT EXISTS (SELECT 1 FROM employees WHERE id = $1)", employee_id)


async def create_deposit(pool: asyncpg.Pool, key: str, body: DepositCreate, amount: Decimal) -> tuple[dict, bool]:
    """Returns (deposit, created). created=False means idempotent replay."""
    req_hash = request_hash(body.employee_id, body.account_id, amount)

    async with pool.acquire() as conn:
        # 1. Fast replay path: key already known -> replay or conflict, regardless of current account state.
        if await conn.fetchval("SELECT EXISTS (SELECT 1 FROM deposits WHERE idempotency_key = $1)", key):
            return await _replay_or_conflict(conn, key, req_hash, body.employee_id), False

        # 2. Business validation (rejected requests do NOT create a deposit record).
        if not await _employee_exists(conn, body.employee_id):
            raise ApiError(404, "EMPLOYEE_NOT_FOUND", f"Employee '{body.employee_id}' does not exist",
                           {"field": "employee_id"})
        account = await conn.fetchrow("SELECT id, status FROM accounts WHERE id = $1", body.account_id)
        if account is None:
            raise ApiError(404, "ACCOUNT_NOT_FOUND", f"Account '{body.account_id}' does not exist",
                           {"field": "account_id"})
        if account["status"] == "BLOCKED":
            raise ApiError(422, "ACCOUNT_BLOCKED", f"Account '{body.account_id}' is blocked and cannot be credited",
                           {"field": "account_id"})

        # 3. One transaction: deposit + RECEIVED event + outbox message.
        deposit_id = uuid.uuid4()
        dispatch_id = uuid.uuid4()
        async with conn.transaction():
            inserted = await conn.fetchval(
                """INSERT INTO deposits (id, idempotency_key, request_hash, employee_id, account_id, amount,
                                         status, current_dispatch_id, simulate_delay_seconds,
                                         simulate_transient_failure)
                   VALUES ($1, $2, $3, $4, $5, $6, 'PENDING', $7, $8, $9)
                   ON CONFLICT (idempotency_key) DO NOTHING
                   RETURNING id""",
                deposit_id, key, req_hash, body.employee_id, body.account_id, amount, dispatch_id,
                body.simulate.delay_seconds, body.simulate.transient_failure,
            )
            if inserted is not None:
                await conn.execute(
                    """INSERT INTO deposit_events (deposit_id, event_type, actor_employee_id, details)
                       VALUES ($1, 'RECEIVED', $2, $3::jsonb)""",
                    deposit_id, body.employee_id,
                    json.dumps({"amount": f"{amount:.2f}", "account_id": body.account_id,
                                "idempotency_key": key, "dispatch_id": str(dispatch_id),
                                "simulate": body.simulate.model_dump()}),
                )
                await conn.execute(
                    """INSERT INTO outbox (deposit_id, message_key, payload) VALUES ($1, $2, $3::jsonb)""",
                    deposit_id, body.account_id,
                    json.dumps({"schema_version": 1, "deposit_id": str(deposit_id),
                                "dispatch_id": str(dispatch_id), "reason": "NEW"}),
                )

        # 4. Lost a concurrent race on the same key -> behave exactly like a replay.
        if inserted is None:
            return await _replay_or_conflict(conn, key, req_hash, body.employee_id), False

        row = await conn.fetchrow(DEPOSIT_SELECT + " WHERE d.id = $1", deposit_id)
        log.info("deposit accepted", extra={"deposit_id": deposit_id, "dispatch_id": dispatch_id,
                                            "employee_id": body.employee_id, "account_id": body.account_id,
                                            "status": "PENDING"})
        return _public(row), True


async def list_deposits(pool: asyncpg.Pool, *, employee_id: str | None, account_id: str | None,
                        statuses: list[str] | None, created_from: date | None, created_to: date | None,
                        idempotency_key: str | None, limit: int, offset: int) -> dict:
    if statuses:
        bad = [s for s in statuses if s not in VALID_STATUSES]
        if bad:
            raise ApiError(422, "INVALID_STATUS", f"Unknown status: {', '.join(bad)}",
                           {"allowed": sorted(VALID_STATUSES)})
    if created_from and created_to and created_from > created_to:
        raise ApiError(422, "INVALID_DATE_RANGE", "created_from must be on or before created_to")

    # Dates are interpreted as calendar days in Israel time; created_to is inclusive (whole day).
    where, args = [], []

    def add(clause: str, value) -> None:
        args.append(value)
        where.append(clause.replace("?", f"${len(args)}"))

    if employee_id:
        add("d.employee_id = ?", employee_id)
    if account_id:
        add("d.account_id = ?", account_id)
    if created_from:
        add("d.created_at >= (?::date::timestamp AT TIME ZONE 'Asia/Jerusalem')", created_from)
    if created_to:
        add("d.created_at < ((?::date + 1)::timestamp AT TIME ZONE 'Asia/Jerusalem')", created_to)
    if idempotency_key:
        add("d.idempotency_key = ?", idempotency_key)

    base_where = " AND ".join(where)
    # Status counts ignore the status filter itself, so the summary tiles stay meaningful.
    counts_sql = f"SELECT d.status, count(*) FROM deposits d {'WHERE ' + base_where if where else ''} GROUP BY d.status"

    if statuses:
        add("d.status = ANY(?::text[])", statuses)
    full_where = ("WHERE " + " AND ".join(where)) if where else ""

    async with pool.acquire() as conn:
        counts_rows = await conn.fetch(counts_sql, *args[: len(args) - (1 if statuses else 0)])
        total = await conn.fetchval(f"SELECT count(*) FROM deposits d {full_where}", *args)
        rows = await conn.fetch(
            DEPOSIT_SELECT + f" {full_where} ORDER BY d.created_at DESC, d.id"
            f" LIMIT ${len(args) + 1} OFFSET ${len(args) + 2}",
            *args, limit, offset,
        )
    status_counts = {s: 0 for s in sorted(VALID_STATUSES)}
    status_counts.update({r["status"]: r["count"] for r in counts_rows})
    return {"items": [_public(r) for r in rows], "total": total, "limit": limit, "offset": offset,
            "status_counts": status_counts}


async def get_deposit(pool: asyncpg.Pool, deposit_id: uuid.UUID) -> dict:
    async with pool.acquire() as conn:
        row = await conn.fetchrow(DEPOSIT_SELECT + " WHERE d.id = $1", deposit_id)
        if row is None:
            raise ApiError(404, "DEPOSIT_NOT_FOUND", f"Deposit {deposit_id} does not exist")
        credit = await conn.fetchrow("SELECT * FROM credits WHERE deposit_id = $1", deposit_id)
        events = await get_events(conn, deposit_id)
    data = _public(row)
    data["credit"] = dict(credit) if credit else None
    data["events"] = events
    return data


async def get_events(conn: asyncpg.Connection, deposit_id: uuid.UUID) -> list[dict]:
    rows = await conn.fetch(
        """SELECT ev.id, ev.event_type, ev.actor_employee_id, e.name AS actor_name, ev.attempt_no,
                  ev.details, ev.created_at
             FROM deposit_events ev
             LEFT JOIN employees e ON e.id = ev.actor_employee_id
            WHERE ev.deposit_id = $1
            ORDER BY ev.created_at, ev.id""",
        deposit_id,
    )
    result = []
    for r in rows:
        item = dict(r)
        item["details"] = json.loads(item["details"]) if isinstance(item["details"], str) else item["details"]
        result.append(item)
    return result
